# NLP训练子模块
# 作用: 提供自然语言处理领域的各类训练器
# 主要接口/类:
#   - SequenceClassificationTrainer: 序列分类训练器
#   - TextRankingTrainer: 文本排序训练器
#   - SiameseUIETrainer: Siamese UIE训练器
#   - TextGenerationTrainer: 文本生成训练器
#   - SentenceEmbeddingTrainer: 句子向量训练器
#   - CsanmtTranslationTrainer: Csanmt翻译训练器
#   - TranslationEvaluationTrainer: 翻译评估训练器
