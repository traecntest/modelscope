# CV训练子模块
# 作用: 提供计算机视觉领域的各类训练器
# 主要接口/类:
#   - ImageInstanceSegmentationTrainer: 图像实例分割训练器
#   - ImagePortraitEnhancementTrainer: 图像人像增强训练器
#   - MovieSceneSegmentationTrainer: 电影场景分割训练器
#   - ImageInpaintingTrainer: 图像修复训练器
#   - ReferringVideoObjectSegmentationTrainer: 视频对象分割训练器
#   - ImageDefrcnFewshotTrainer: Defrcn少样本检测训练器
#   - CartoonTranslationTrainer: 卡通翻译训练器
#   - OCRRecognitionTrainer: OCR识别训练器
#   - NeRFReconAccTrainer: NeRF重建训练器
#   - VisionEfficientTuningTrainer: 视觉高效调优训练器
