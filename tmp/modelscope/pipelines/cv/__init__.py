# CV流水线子模块
# 作用: 提供计算机视觉领域的各类推理流水线
# 主要接口/类:
#   - ImageClassificationPipeline: 图像分类流水线
#   - FaceDetectionPipeline: 人脸检测流水线
#   - FaceRecognitionPipeline: 人脸识别流水线
#   - ObjectDetection3DPipeline: 3D目标检测流水线
#   - ImageInstanceSegmentationPipeline: 图像实例分割流水线
#   - ImageSemanticSegmentationPipeline: 图像语义分割流水线
#   - ImageSuperResolutionPipeline: 图像超分辨率流水线
#   - ImageDenoisePipeline: 图像去噪流水线
#   - ImageColorEnhancePipeline: 图像色彩增强流水线
#   - VideoSuperResolutionPipeline: 视频超分辨率流水线
#   - VideoStabilizationPipeline: 视频稳像流水线
#   - ActionRecognitionPipeline: 动作识别流水线
#   - OCRDetectionPipeline, OCRRecognitionPipeline: OCR检测/识别流水线
#   等上百种CV任务流水线
