# 多模态流水线子模块
# 作用: 提供多模态领域的各类推理流水线
# 主要接口/类:
#   - AutomaticSpeechRecognitionPipeline: 自动语音识别流水线
#   - ChineseStableDiffusionPipeline: 中文StableDiffusion流水线
#   - StableDiffusionPipeline: StableDiffusion流水线
#   - DocumentVLEmbeddingPipeline: 文档视觉语言嵌入流水线
#   - GEMMMultiModalEmbeddingPipeline: GEMM多模态嵌入流水线
#   - ImageCaptioningPipeline: 图像字幕流水线
#   - MGeoRankingPipeline: MGeo排序流水线
#   - MultiModalEmbeddingPipeline: 多模态嵌入流水线
#   - MultimodalDialoguePipeline: 多模态对话流水线
#   - ProSTTextVideoRetrievalPipeline: ProST文本视频检索流水线
#   - SOONetVideoTemporalGroundingPipeline: SOONet视频时序定位流水线
#   - TextToImageSynthesisPipeline: 文本生成图像流水线
#   - TextToVideoSynthesisPipeline: 文本生成视频流水线
#   - VideoCaptioningPipeline: 视频字幕流水线
#   - VideoMultiModalEmbeddingPipeline: 视频多模态嵌入流水线
#   - VisualQuestionAnsweringPipeline: 视觉问答流水线
#   - VideoQuestionAnsweringPipeline: 视频问答流水线
#   - VideoComposerPipeline: 视频合成流水线
#   - FreeUTextToImagePipeline: FreeU文本生成图像流水线
#   - VisualEntailmentPipeline: 视觉蕴含流水线
#   - VisualGroundingPipeline: 视觉定位流水线
