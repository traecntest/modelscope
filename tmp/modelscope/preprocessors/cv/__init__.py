# CV数据预处理子模块
# 作用: 提供计算机视觉领域的数据预处理功能
# 主要接口/类:
#   - ImageClassificationMmcvPreprocessor: 图像分类预处理
#   - ImageRestorationPreprocessor: 图像恢复预处理
#   - ControllableImageGenerationPreprocessor: 可控图像生成预处理
#   - ImageQualityAssessmentMosPreprocessor: 图像质量评估MOS预处理
#   - ImageQualityAssessmentMANPreprocessor: 图像质量评估MAN预处理
#   - BadImageDetectingPreprocessor: 坏图检测预处理
#   - VideoReader: 视频读取预处理
#   - stabilization_preprocessor: 视频稳像预处理
