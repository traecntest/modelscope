# OFA预处理子模块
# 作用: 提供OFA模型的各类任务数据预处理功能
# 主要接口/类:
#   - OfaASRPreprocessor: OFA语音识别预处理器
#   - OfaImageCaptioningPreprocessor: OFA图像字幕预处理器
#   - OfaImageClassificationPreprocessor: OFA图像分类预处理器
#   - OfaOcrRecognitionPreprocessor: OFA OCR识别预处理器
#   - OfaSudokuPreprocessor: OFA数独预处理器
#   - OfaSummarizationPreprocessor: OFA摘要预处理器
#   - OfaTextToSqlPreprocessor: OFA文本转SQL预处理器
#   - OfaTextClassificationPreprocessor: OFA文本分类预处理器
#   - OfaTextToImageSynthesisPreprocessor: OFA文本生成图像预处理器
#   - OfaVisualEntailmentPreprocessor: OFA视觉蕴含预处理器
#   - OfaVisualGroundingPreprocessor: OFA视觉定位预处理器
#   - OfaVisualQuestionAnsweringPreprocessor: OFA视觉问答预处理器
