# 多模态模型子模块
# 作用: 提供多模态领域的各类模型定义
# 主要接口/类:
#   - CLIPForMultiModalEmbedding: CLIP多模态嵌入模型
#   - CLIP_Interrogator: CLIP Interrogator模型
#   - DiffusionForTextToImageSynthesis: Diffusion文本生成图像模型
#   - EfficientStableDiffusion: 高效StableDiffusion模型
#   - GEMMForMultiModalEmbedding: GEMM多模态嵌入模型
#   - VideoCLIPForMultiModalEmbedding: VideoCLIP多模态嵌入模型
#   - MPlugForAllTasks, HiTeAForAllTasks: MPlug多任务模型
#   - MplugOwlForConditionalGeneration: MPLUG-Owl条件生成模型
#   - MultiStageDiffusionForTextToImageSynthesis: 多阶段Diffusion文本生成图像模型
#   - OfaForAllTasks: OFA多任务模型
#   - OfaForTextToImageSynthesis: OFA文本生成图像模型
#   - ProSTForTVRetrieval: ProST文本视频检索模型
#   - RLEGForMultiModalEmbedding: RLEG多模态嵌入模型
#   - TEAMForMultiModalSimilarity: TEAM多模态相似性模型
#   - TextToVideoSynthesis: 文本生成视频模型
#   - VLDocForDocVLEmbedding: VLDoc文档视觉语言嵌入模型
#   - VideoComposer: 视频合成模型
